import csv, json, os, pprint
SRC = os.path.join(os.environ["TEMP"], "pyro_ref")
REFS = [("CI Chondrite (McDonough & Sun 1995)", "CH_McDonoughSun1995"),
        ("Primitive Mantle (McDonough & Sun 1995)", "PY_McDonoughSun1995"),
        ("N-MORB (Sun & McDonough 1989)", "NMORB_SunMcDonough1989"),
        ("OIB (Sun & McDonough 1989)", "OIB_SunMcDonough1989"),
        ("Upper Continental Crust (Rudnick & Gao 2003)", "UCC_RudnickGao2003"),
        ("PAAS (Taylor & McLennan 1985)", "PAAS_TaylorMcLennan1985")]
refs, cites = {}, {}
for label, f in REFS:
    vals = {}
    for row in csv.DictReader(open(os.path.join(SRC, f + ".csv"), encoding="utf-8")):
        if row["var"] == "Citation": cites[label] = row["value"]
        if row["var"] == "DOI" and row["value"]: cites[label] += f" doi:{row['value']}"
        try: v = float(row["value"])
        except (TypeError, ValueError): continue
        u = (row.get("units") or "").strip()
        if u == "ppm": vals[row["var"]] = v
        elif u == "ppb": vals[row["var"]] = v / 1000
    refs[label] = vals
tas = json.load(open(os.path.join(SRC, "pyrolite_data_models_TAS_config.json")))
TAS = {v["name"][0].replace("\n", "").replace("- ", "").replace("-", "") if isinstance(v["name"], list) else v["name"]: v["poly"]
       for k, v in tas["fields"].items() if v["poly"]}
qap = json.load(open(os.path.join(SRC, "QAP.json")))
QAP = {v["name"]: v["poly"] for v in qap["fields"].values()}
QAP["Quartz Alkali Feldspar Syenite"] = QAP.pop("Quartz Alkali Feldspar Granite")  # label typo in the source file
out = '''"""Reference compositions and classification fields for geochemical plots.

Author: Kishan Tiwari <kishantiwari@iitkgp.ac.in>
Values (ppm) and field polygons are taken from the pyrolite project (MIT License, Copyright (c) 2018 CSIRO; https://github.com/morganjwilliams/pyrolite; see THIRD_PARTY_NOTICES.md),
which compiles them from the publications cited in CITATIONS. TAS: Le Bas et al. (1986) J. Petrol. 27, 745-750 (with
Middlemost 1994 picrite field). QAP: Streckeisen (1976) Earth-Sci. Rev. 12, 1-33; polygons are [Q, A, P] in percent.
Generated by make_geodata.py; do not edit by hand.
"""

# Element order for multi-element (spider) plots: REE by atomic number; extended set by incompatibility (Sun & McDonough 1989)
REE = ["La", "Ce", "Pr", "Nd", "Pm", "Sm", "Eu", "Gd", "Tb", "Dy", "Ho", "Er", "Tm", "Yb", "Lu"]
SPIDER_ORDER = ["Cs", "Rb", "Ba", "Th", "U", "Nb", "Ta", "K", "La", "Ce", "Pb", "Pr", "Sr", "P", "Nd", "Zr", "Hf", "Sm", "Eu", "Ti",
                "Gd", "Tb", "Dy", "Y", "Ho", "Er", "Tm", "Yb", "Lu"]

'''
out += "REFERENCES = " + pprint.pformat(refs, width=130, sort_dicts=False) + "\n\n"
out += "CITATIONS = " + pprint.pformat(cites, width=130, sort_dicts=False) + "\n\n"
out += "TAS_FIELDS = " + pprint.pformat(TAS, width=130, sort_dicts=False) + "\n\n"
out += "QAP_FIELDS = " + pprint.pformat(QAP, width=130, sort_dicts=False) + "\n"
open(r"E:\PHD\PlotBench\plotbench\geodata.py", "w", encoding="utf-8").write(out)
